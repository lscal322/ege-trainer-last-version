def _upsert(conn, table, key_columns, values, update_columns):
    where = ' AND '.join(f'{column}=?' for column in key_columns)
    key_values = tuple(values[column] for column in key_columns)
    row = conn.execute(f'SELECT id FROM {table} WHERE {where}', key_values).fetchone()
    if row:
        assignments = ','.join(f'{column}=?' for column in update_columns)
        conn.execute(
            f'UPDATE {table} SET {assignments} WHERE id=?',
            tuple(values[column] for column in update_columns) + (row[0],),
        )
    else:
        columns = list(values)
        placeholders = ','.join('?' for _ in columns)
        conn.execute(
            f'INSERT INTO {table}({",".join(columns)}) VALUES({placeholders})',
            tuple(values[column] for column in columns),
        )


