def build_essay_prompt_bank():
    """Build 200 original study prompts; these are not official FIPI texts."""
    prompts = []
    index = 0
    for theme in _THEMES:
        for scene_index, scene in enumerate(theme['scenes']):
            for variation in range(2):
                index += 1
                name = _NAMES[scene_index * 2 + variation]
                source = (
                    scene.format(name=name)
                    + ' '
                    + _REFLECTIONS[variation]
                )
                title = f'Учебный текст {index:03d} · {theme["title"]}'
                problem = theme['problem']
                task = (
                    f'Напишите сочинение-рассуждение по проблеме: «{problem}». '
                    'Сформулируйте позицию автора, приведите два примера из текста, '
                    'поясните их и назовите смысловую связь. Выразите и обоснуйте '
                    'своё отношение к позиции автора.'
                )
                analysis = (
                    f'Проблема текста: {problem}.\n'
                    f'Возможная позиция автора: {theme["position"]}.\n'
                    'План разбора:\n'
                    '1. В первом примере назовите исходную ситуацию и трудность героя.\n'
                    '2. Во втором примере разберите его решение и последствия.\n'
                    '3. Связь между примерами можно объяснить как причину и следствие: '
                    'поступок раскрывает смысл пережитого события.\n'
                    '4. Не подменяйте комментарий пересказом: после каждого примера '
                    'объясните, что он показывает.\n'
                    '5. Сформулируйте собственное отношение и приведите отдельное '
                    'обоснование. Это авторский учебный текст, а не официальный вариант КИМ.'
                )
                prompts.append({
                    'title': title,
                    'source_text': source,
                    'problem': task,
                    'analysis': analysis,
                })
    return prompts


def seed_essay_prompt_bank(conn):
    rows = build_essay_prompt_bank()
    added = 0
    for prompt in rows:
        existing = conn.execute(
            'SELECT id FROM essay_prompts WHERE title=?', (prompt['title'],)
        ).fetchone()
        if existing:
            conn.execute(
                'UPDATE essay_prompts SET source_text=?,problem=?,analysis=? WHERE id=?',
                (prompt['source_text'], prompt['problem'], prompt['analysis'], existing[0]),
            )
        else:
            conn.execute(
                'INSERT INTO essay_prompts(title,source_text,problem,analysis) VALUES(?,?,?,?)',
                (prompt['title'], prompt['source_text'], prompt['problem'], prompt['analysis']),
            )
            added += 1
    return added
